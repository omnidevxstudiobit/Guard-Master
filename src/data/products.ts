/**
 * Pull one specific shot out of a group. Sections that need a particular
 * image (the factory floor, a specific roll stack) reach for this rather than
 * indexing into `images[3]` — an array position silently points at a
 * different photo the moment the manifest is reordered, whereas a missing id
 * returns undefined and the calling template skips the slot.
 */
export const findImage = (slug: string, id: string): ProductImage | undefined =>
  images(slug).find((image) => image.id === id);

export const productBySlug = (slug: string): Product | undefined =>
  PRODUCTS.find((product) => product.slug === slug);
