import IMAGE_INDEX from './product-images.json';

/**
 * The product catalogue.
 *
 * **Four families, not eight SKUs.** An earlier pass listed every purchasable
 * line — panels, posts, clamps, spikes, mesh, mesh posts, coils, temporary —
 * as a peer of every other, which put a R 8,06 clamp on the same footing as a
 * whole fencing system and buried what the business actually sells. What it
 * sells is four things: Clear View fencing, razor wire mesh, concertina razor
 * wire, and temporary fencing. Everything else is a component *inside* one of
 * those, and lives in `Product.includes` — which is also the shape the product
 * pages need, since each one opens on its family and then breaks down into
 * exactly these parts.
 *
 * **Photography** comes from `product-images.json`, generated by
 * `scripts/build-product-images.mjs` from the client's "Products 2026" drop.
 * Never hand-edit that JSON — re-run `npm run images`, or the `src`/`srcset`
 * and dimensions drift from the files on disk. Each group is ordered
 * render-first: `images[0]` is the studio engineering render of the assembly,
 * because that is what the range section shows at full size.
 *
 * **Prices** are the client's own published list prices, read off their live
 * storefront (fencing-supplier.com) product by product. ZAR, VAT-inclusive
 * (that storefront prints "R1884,45 Incl. Vat"), and each is a *from* price —
 * the lowest variation of a configurable product, not a flat rate. A family's
 * `priceFrom` is its headline component's from-price: the panel for Clear
 * View, the sheet for razor wire mesh, the coil for concertina.
 *
 * `unit` is only filled where the storefront's own quantity and attribute
 * labels confirm what is being counted ("Clear View Fencing Panels quantity",
 * attributes Aperture / Panel Size / Wire Size / Finishing → per panel).
 * Where it isn't confirmed it stays null and the UI shows a bare "from",
 * rather than inventing a per-metre basis that would be wrong on an invoice.
 * Temporary fencing carries no price at all, because that storefront publishes
 * none for its rapid-deployment range — it renders as "Price on request",
 * which is true, instead of a number that isn't.
 *
 * Metric and ZAR throughout, matching the real business: a Benoni, Gauteng
 * manufacturer quoting in rand.
 */

export interface ProductImage {
  id: string;
  alt: string;
  src: string;
  width: number;
  height: number;
  srcset: string;
}

/** A purchasable component inside a family. */
export interface Component {
  name: string;
  /** Null until that component has a page of its own. */
  href: string | null;
  note: string;
  priceFrom: number | null;
  unit: string | null;
}

export interface Product {
  slug: string;
  /** Where the family links. Families without a page yet route to the estimator. */
  href: string;
  /** True once a dedicated page covers this family. */
  hasPage: boolean;
  name: string;
  /** Short label for rails and cards, where the full name is too long. */
  shortName: string;
  /** One-line positioning, used as the card's kicker. */
  tagline: string;
  blurb: string;
  /** Headline component's from-price, in rand, VAT inclusive. */
  priceFrom: number | null;
  unit: string | null;
  /** Three headline specs — what a buyer scans for. */
  specs: string[];
  /** The parts that make up the family. */
  includes: Component[];
  /**
   * Which technical drawing represents this family in the range section. The
   * four drawings are line art (ui/ProductDrawing.astro), not photographs:
   * four products shot by four people in four conditions never read as one
   * system, and drawing them puts the range in the same language as the rest
   * of the site's cutaways and schematics.
   */
  drawing: 'clear-view' | 'razor-mesh' | 'concertina' | 'temporary';
  /** Text alternative for that drawing — it's content, not decoration. */
  drawingLabel: string;
  /** Client photography, still used by the product pages and galleries. */
  images: ProductImage[];
}

const images = (slug: string): ProductImage[] =>
  (IMAGE_INDEX as Record<string, ProductImage[]>)[slug] ?? [];

/**
 * Rand formatting — comma thousands, period decimal ("R 1,106.00").
 *
 * This is the format the client quotes customers in: their instant-quote
 * estimator prints "Clear view panel 3m W x 1.8m H, plain galv. => R 1,106.00"
 * on every option, and their PDF quote follows it. An earlier version here used
 * the space-and-comma convention ("R 1 884,45") taken from their WooCommerce
 * shop pages — also genuinely theirs, but the wrong one to copy: a price on our
 * page has to match the quote a customer is holding, and they can't be shown
 * the same panel in two notations.
 *
 * `en-US` is the grouping locale, not the currency — the "R" prefix is written
 * explicitly so no locale can substitute a symbol.
 */
export const formatRand = (amount: number): string =>
  `R ${new Intl.NumberFormat('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount)}`;

/** "From R 550.85 per panel" / "Price on request". */
export const priceLabel = (item: { priceFrom: number | null; unit: string | null }): string => {
  if (item.priceFrom === null) return 'Price on request';
  return `From ${formatRand(item.priceFrom)}${item.unit ? ` ${item.unit}` : ''}`;
};

